import { z } from 'zod'
import { LUCIDE_ICONS } from '../icons/lucideSet'
import { VENDOR_CATEGORIES, VENDOR_ICONS } from '../icons/vendorSet'
import { Doc } from './schema'

export const SCHEMA_PATH = 'schema/archipen.schema.json'
/** Where the Pages site serves the schema (scripts/site.mjs copies schema/ there). */
export const SCHEMA_URL = 'https://archipen.dev/schema/archipen.schema.json'

type Json = { [k: string]: unknown }

/**
 * The JSON Schema for `*.archipen.json`, generated from the zod schema (input side, so fields
 * with defaults are optional). Written to schema/archipen.schema.json by `npm run schema`.
 */
export function buildJsonSchema(): Json {
  const schema = z.toJSONSchema(Doc, { io: 'input', target: 'draft-2020-12' }) as Json
  const icons = [
    ...Object.keys(LUCIDE_ICONS)
      .sort()
      .map((n) => `lucide:${n}`),
    ...Object.keys(VENDOR_ICONS)
      .sort()
      .map((n) => `vendor:${n}`),
  ]

  const visit = (node: unknown): unknown => {
    if (Array.isArray(node)) return node.map(visit)
    if (!node || typeof node !== 'object') return node
    const n = node as Json
    // Icon fields: list the built-in names so generators can't invent one.
    if (n['x-archipen-icon']) {
      const allowEmpty = String(n.pattern ?? '').startsWith('^((')
      return {
        description: n.description,
        anyOf: [{ enum: allowEmpty ? ['', ...icons] : icons }, { type: 'string', pattern: '^custom:.+$' }],
      }
    }
    const out: Json = {}
    for (const [k, v] of Object.entries(n)) out[k] = k === 'properties' ? Object.fromEntries(Object.entries(v as Json).map(([pk, pv]) => [pk, visit(pv)])) : visit(v)
    // Unknown keys are dropped on load, so a typo like "colour" would silently do nothing: reject them.
    if (n.type === 'object' && n.properties && n.additionalProperties === undefined) out.additionalProperties = false
    return out
  }

  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: SCHEMA_URL,
    title: 'Archipen diagram',
    ...(visit(schema) as Json),
  }
}

export const jsonSchemaText = () => JSON.stringify(buildJsonSchema(), null, 2) + '\n'

export const DOCS_PATH = 'docs/file-format.md'
const ICONS_START = '<!-- icons:start (generated by `npm run schema`) -->'
const ICONS_END = '<!-- icons:end -->'
const VENDOR_START = '<!-- vendor-icons:start (generated by `npm run schema`) -->'
const VENDOR_END = '<!-- vendor-icons:end -->'

const codeList = (names: string[]) => names.map((n) => '`' + n + '`').join(', ')

function replaceBlock(markdown: string, start: string, end: string, list: string): string {
  const a = markdown.indexOf(start)
  const b = markdown.indexOf(end)
  if (a < 0 || b < a) throw new Error(`${DOCS_PATH} is missing the markers ${start} … ${end}`)
  return markdown.slice(0, a) + `${start}\n${list}\n${end}` + markdown.slice(b + end.length)
}

/** Replace the generated icon lists in docs/file-format.md with the current built-in and vendor icon names. */
export function withIconList(markdown: string): string {
  const lucide = replaceBlock(markdown, ICONS_START, ICONS_END, codeList(Object.keys(LUCIDE_ICONS).sort()))
  const vendors = VENDOR_CATEGORIES.map((c) => {
    const names = Object.keys(VENDOR_ICONS).filter((n) => VENDOR_ICONS[n].category === c)
    return `- **${c}:** ${codeList(names.sort())}`
  }).join('\n')
  return replaceBlock(lucide, VENDOR_START, VENDOR_END, vendors)
}
