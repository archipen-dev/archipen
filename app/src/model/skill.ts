// The agent skill in skills/archipen/: SKILL.md is hand-written except for the rules block, which comes from the
// "Prompt for AI generation" in docs/file-format.md. The reference files are copies of the docs, schema and examples.
// `npm run schema` writes them; format.test.ts fails when they are out of date.
import { DOCS_PATH, SCHEMA_PATH } from './jsonSchema'

export const SKILL_DIR = 'skills/archipen'
const SKILL_MD = `${SKILL_DIR}/SKILL.md`
const EXAMPLES = ['minimal', 'web-shop', 'drill-down']
const REPO_URL = 'https://github.com/archipen-dev/archipen/blob/main/'
const SITE_URL = 'https://archipen.dev/'

const RULES_START = '<!-- rules:start (generated by `npm run schema` from docs/file-format.md) -->'
const RULES_END = '<!-- rules:end -->'
const GENERATED = '<!-- Generated by `npm run schema` from docs/file-format.md. Do not edit. -->'

/** The rules from the docs' AI prompt, adjusted for an agent that writes a file and has the reference files. */
export function skillRules(docs: string): string {
  const prompt = /## Prompt for AI generation[\s\S]*?```text\n([\s\S]*?)```/.exec(docs)?.[1]
  if (!prompt) throw new Error(`${DOCS_PATH} has no "Prompt for AI generation" text block`)
  return prompt
    .split('\n')
    .filter((line) => line.trim() && !line.startsWith('Create an Archipen diagram') && line.trim() !== '- Output only the JSON.')
    .join('\n')
    .replace('<ICON LIST>', 'the "Built-in icons" list in references/format.md')
    .replace('<VENDOR LIST>', 'the "Vendor icons" list in references/format.md')
}

function withRules(skillMd: string, docs: string): string {
  const a = skillMd.indexOf(RULES_START)
  const b = skillMd.indexOf(RULES_END)
  if (a < 0 || b < a) throw new Error(`${SKILL_MD} is missing the markers ${RULES_START} … ${RULES_END}`)
  return skillMd.slice(0, a) + `${RULES_START}\n${skillRules(docs)}\n${RULES_END}` + skillMd.slice(b + RULES_END.length)
}

/** The docs page, with links that still work outside the repository. */
function formatReference(docs: string): string {
  const body = docs
    .replace(/\]\(\.\.\//g, `](${REPO_URL}`)
    .replace(/\]\(([a-z-]+)\.md(#[^)]*)?\)/g, (_, page: string, hash = '') => `](${SITE_URL}${page}${hash})`)
  return `${GENERATED}\n\n${body}`
}

/**
 * Every generated file of the skill, by path from the repository root. `read` returns a committed file's text
 * (SKILL.md, the docs, the schema and the examples).
 */
export function skillFiles(read: (path: string) => string): Record<string, string> {
  const docs = read(DOCS_PATH)
  const files: Record<string, string> = {
    [SKILL_MD]: withRules(read(SKILL_MD), docs),
    [`${SKILL_DIR}/references/format.md`]: formatReference(docs),
    [`${SKILL_DIR}/assets/archipen.schema.json`]: read(SCHEMA_PATH),
  }
  for (const name of EXAMPLES) {
    const example = read(`examples/${name}.archipen.json`).replace('"../schema/archipen.schema.json"', '"../../assets/archipen.schema.json"')
    files[`${SKILL_DIR}/references/examples/${name}.archipen.json`] = example
  }
  return files
}
